  const languages = ["zh-Hant", "en", "ja", "ko"];
  const select = document.getElementById("languageSelect");
  const pageTranslations = pages[pageKey] || {};
  let currentLanguage = localStorage.getItem(storageKey) || "zh-Hant";
  if (!languages.includes(currentLanguage)) currentLanguage = "zh-Hant";

  function lookup(key) {
    return pageTranslations[currentLanguage]?.[key]
      || common[currentLanguage]?.[key]
      || pageTranslations["zh-Hant"]?.[key]
      || common["zh-Hant"]?.[key]
      || key;
  }

  function applyLanguage(language) {
    currentLanguage = languages.includes(language) ? language : "zh-Hant";
    localStorage.setItem(storageKey, currentLanguage);
    document.documentElement.lang = currentLanguage;
    document.title = lookup("documentTitle");
    if (select) select.value = currentLanguage;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = lookup(element.dataset.i18n);
    });
  }

  if (select) {
    select.addEventListener("change", () => applyLanguage(select.value));
  }
  applyLanguage(currentLanguage);
